"""Fixed explanation texts for pipeline events.

These are written by hand on purpose: they must always be correct and
instant, so they are not generated by an AI model.
Each explanation has two parts: what happened, and why we do it.
"""
from __future__ import annotations

from dataclasses import dataclass

from .translation import Event


@dataclass
class Explanation:
    what: str
    why: str


_TEMPLATES: dict[str, Explanation] = {
    "normalized": Explanation(
        what="Satırlar birleştirildi, fazla boşluklar silindi.",
        why="Altyazılar genelde iki satırdır ve satır sonu cümlenin ortasına düşebilir. "
        "Çeviriye tek cümle gitmezse anlam bozulur.",
    ),
    "repeat_skipped": Explanation(
        what="Aynı altyazı tekrar geldi, yeniden çevrilmedi.",
        why="Kamera aynı altyazıyı ekranda kaldığı sürece saniyede onlarca kez görür. "
        "Her seferinde çevirmek hem yavaşlatır hem de çeviri servisinden engellenme riskini artırır.",
    ),
    "cache_hit": Explanation(
        what="Bu cümle daha önce çevrilmişti, kayıttan alındı ({ms:.1f} ms).",
        why="Oyunlarda aynı replikler tekrar eder (\"Let's go\", menü yazıları). "
        "Kayıttan almak anlıktır ve servise istek göndermez.",
    ),
    "engine_call": Explanation(
        what="Cümle {engine} motoruna gönderildi.",
        why="Yeni bir cümle geldi ve daha önce çevrilmemiş, o yüzden çeviri motoruna soruyoruz.",
    ),
    "translated": Explanation(
        what="{engine} çeviriyi {ms:.0f} ms içinde döndürdü.",
        why="Süreyi ölçüyoruz, çünkü altyazı ekranda birkaç saniye kalıyor. "
        "Çeviri ondan kısa sürmeli ki İngilizcesi kaybolmadan Türkçesi gelsin.",
    ),
    "engine_error": Explanation(
        what="{engine} hata verdi: {error}",
        why="İnternet kesilmiş ya da servis geçici olarak engellemiş olabilir. "
        "Uygulama durmaz; aynı cümle tekrar gelirse yeniden denenir.",
    ),
}


def explain(event: Event) -> Explanation:
    template = _TEMPLATES.get(event.code)
    if template is None:
        return Explanation(what=event.code, why="")
    try:
        return Explanation(what=template.what.format(**event.detail), why=template.why)
    except (KeyError, ValueError):
        return template
